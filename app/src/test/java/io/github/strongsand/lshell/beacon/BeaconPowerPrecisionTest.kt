package io.github.strongsand.lshell.beacon

import java.util.Locale
import org.json.JSONArray
import org.json.JSONObject
import org.junit.Assert.*
import org.junit.Test

class BeaconPowerPrecisionTest {
    private fun cases() = javaClass.getResourceAsStream("/beacon_lab_precision.json")!!
        .bufferedReader().use { JSONArray(it.readText()) }

    @Test fun actualLabEngineJsonKeepsRawVoltageCurrentPowerAndCaptureTogether() {
        val cases = cases()
        for (i in 0 until cases.length()) {
            val status = cases.getJSONObject(i).getJSONObject("status")
            val raw = status.getJSONObject("electrical")
            val payload = BeaconPowerParser.parse(status, setOf(POWER_SIMULATION_CAPABILITY))
            assertEquals(BeaconPowerCondition.VALID, payload.condition)
            val reading = payload.reading!!
            assertEquals(raw.getDouble("voltage_v"), reading.voltageV!!, 0.0)
            assertEquals(raw.getDouble("current_a"), reading.currentA!!, 0.0)
            assertEquals(raw.getDouble("power_w"), reading.powerW!!, 0.0)
            assertEquals(raw.getDouble("energy_wh"), reading.energyWh!!, 0.0)
            assertEquals(raw.getLong("capture_uptime_ms"), reading.captureUptimeMs)
            assertEquals(raw.getLong("boot_id"), reading.bootId)
        }
        val constant = BeaconPowerParser.parse(cases.getJSONObject(0).getJSONObject("status"), setOf(POWER_SIMULATION_CAPABILITY)).reading!!
        assertEquals(24.123, constant.voltageV!!, 0.0) // Lab's configured 24.1234 is quantized before JSON
        assertEquals(1.568, constant.currentA!!, 0.0)
    }

    @Test fun presentationPrecisionDoesNotAlterTheUnderlyingSampleOrHideSmallNonzeroValues() {
        val original = Locale.getDefault()
        try {
            Locale.setDefault(Locale.US)
            val r = BeaconPowerParser.parse(cases().getJSONObject(0).getJSONObject("status"), setOf(POWER_SIMULATION_CAPABILITY)).reading!!
            assertEquals("24.123", formatBeaconPowerNumber(r.voltageV!!, 3))
            assertEquals("1.568", formatBeaconPowerNumber(r.currentA!!, 3))
            assertEquals("0.0000", formatBeaconPowerNumber(0.0, 4))
            assertNotEquals("0.000", formatBeaconPowerNumber(1e-9, 3))
            assertNotEquals("-0.000", formatBeaconPowerNumber(-1e-9, 3))
            assertEquals(24.123, r.voltageV!!, 0.0)
        } finally { Locale.setDefault(original) }
    }

    @Test fun tinySignedChartRangesUseTheirActualScaleInsteadOfAOneWattFloor() {
        val scale = beaconPowerPlotScale(listOf(-.04, 0.0, .02))
        assertEquals(-.04, scale.low, 0.0); assertEquals(.02, scale.high, 0.0)
        assertEquals(.06, scale.span, 1e-15)
        val voltage = beaconPowerPlotScale(listOf(.001, .002))
        assertEquals(0.0, voltage.low, 0.0); assertEquals(.002, voltage.span, 0.0)
        assertTrue(beaconPowerPlotScale(listOf(0.0)).span > 0)
        assertTrue(beaconPowerPlotScale(emptyList()).span > 0)
    }

    @Test fun differentDynamicSnapshotsAreNotSubstitutedByNominalOrOtherCaptureValues() {
        val cases = cases()
        val first = BeaconPowerParser.parse(cases.getJSONObject(0).getJSONObject("status"), setOf(POWER_SIMULATION_CAPABILITY))
        val sine = BeaconPowerParser.parse(cases.getJSONObject(2).getJSONObject("status"), setOf(POWER_SIMULATION_CAPABILITY))
        val before = BeaconPowerSession().accept("lab", first, 0)
        val after = before.accept("lab", sine, 16_000)
        assertEquals(24.123, before.payload.reading!!.voltageV!!, 0.0)
        assertEquals(28.0, after.visible(16_000)!!.voltageV!!, 0.0)
        assertEquals(2.0, after.visible(16_000)!!.currentA!!, 0.0)
        assertEquals(56.0, after.visible(16_000)!!.powerW!!, 0.0)
        assertTrue(after.points.last().breakBefore) // actual 16-second capture gap stays a gap
    }

    @Test fun actualCppSerialSensorJsonPassesTheSameAndroidParserWithoutUnitOrSignChanges() {
        // Fixture generated by power_serial_json(): production serial input + production encoder/WASM.
        val status = javaClass.getResourceAsStream("/beacon_serial_status_v1.json")!!.bufferedReader()
            .use { JSONObject(it.readText()) }
        val payload = BeaconPowerParser.parse(status, setOf(POWER_SIMULATION_CAPABILITY))
        assertEquals(BeaconPowerCondition.VALID, payload.condition)
        val r = payload.reading!!
        assertEquals(24.1234, r.voltageV!!, 0.0)
        assertEquals(-1.5678, r.currentA!!, 0.0)
        assertTrue(r.powerW!! < 0 && r.energyWh!! < 0)
        assertEquals(24.1234 * -1.5678 / 3600, r.energyWh!!, 1e-10)
        assertEquals(2000L, r.captureUptimeMs)
        assertEquals(BeaconPowerOrigin.SIMULATED, r.origin)
    }
}
